"""Stage 2/3: file discovery and language identification."""
from __future__ import annotations

import os
from collections import Counter

from ..config import BINARY_EXTENSIONS, IGNORED_DIRS, IGNORED_FILENAMES, IGNORED_SUFFIXES
from ..models.source import SourceFile
from .languages import IGNORED_TEXT_EXTENSIONS, detect_language

NOISE_FILES = {".gitignore", ".gitattributes", ".editorconfig", ".dockerignore", ".npmignore", "license", "licence",
               "copying", "notice", "authors", "codeowners", ".prettierignore", ".eslintignore", ".nvmrc"}
GENERATED_MARKERS = ("auto-generated", "autogenerated", "@generated", "do not edit", "generated by")


def looks_binary(sample: bytes) -> bool:
    if b"\x00" in sample:
        return True
    if not sample:
        return False
    text_chars = bytes(range(32, 127)) + b"\n\r\t\f\b"
    nontext = sum(1 for b in sample if b < 128 and b not in text_chars)
    return nontext / len(sample) > 0.30


def discover(root: str, max_file_bytes: int) -> tuple[list[SourceFile], list[dict], dict]:
    """Walk `root` and return (source files, skipped entries, language stats)."""
    files: list[SourceFile] = []
    skipped: list[dict] = []
    root = os.path.realpath(root)
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d not in IGNORED_DIRS and not d.endswith(".egg-info"))
        for fn in sorted(filenames):
            abs_path = os.path.join(dirpath, fn)
            rel = os.path.relpath(abs_path, root).replace(os.sep, "/")
            if os.path.islink(abs_path):
                skipped.append({"file": rel, "reason": "symlink"})
                continue
            low = fn.lower()
            ext = os.path.splitext(low)[1]
            if fn in IGNORED_FILENAMES or low.endswith(IGNORED_SUFFIXES):
                skipped.append({"file": rel, "reason": "generated/lock file"})
                continue
            if ext in BINARY_EXTENSIONS:
                skipped.append({"file": rel, "reason": "binary"})
                continue
            if low in NOISE_FILES or (ext in IGNORED_TEXT_EXTENSIONS and detect_language(rel) is None):
                skipped.append({"file": rel, "reason": "documentation/data"})
                continue
            try:
                size = os.path.getsize(abs_path)
                if size > max_file_bytes:
                    skipped.append({"file": rel, "reason": "too large"})
                    continue
                with open(abs_path, "rb") as fh:
                    raw = fh.read()
            except OSError:
                skipped.append({"file": rel, "reason": "unreadable"})
                continue
            if looks_binary(raw[:8000]):
                skipped.append({"file": rel, "reason": "binary"})
                continue
            text = raw.decode("utf-8", errors="replace")
            head = "\n".join(text.splitlines()[:5]).lower()
            if any(m in head for m in GENERATED_MARKERS) and ("generated" in head):
                skipped.append({"file": rel, "reason": "generated file"})
                continue
            files.append(SourceFile(abs_path=abs_path, rel=rel, language=detect_language(rel), text=text, size=size))
    return files, skipped, language_stats(files)


def language_stats(files: list[SourceFile]) -> dict:
    by_lang: dict[str, dict] = {}
    unsupported: Counter = Counter()
    for f in files:
        if f.language is None:
            unsupported[os.path.splitext(f.rel)[1].lower() or os.path.basename(f.rel)] += 1
            continue
        d = by_lang.setdefault(f.language.name, {"language": f.language.name, "files": 0, "lines": 0,
                                                 "support": f.language.support, "kind": f.language.kind})
        d["files"] += 1
        d["lines"] += len(f.text.splitlines())
    return {
        "languages": sorted(by_lang.values(), key=lambda d: -d["lines"]),
        "unsupported": [{"extension": k, "files": v} for k, v in unsupported.most_common()],
    }
